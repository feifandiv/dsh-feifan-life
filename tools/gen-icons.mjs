/**
 * Generates `shim/icons.generated.ts` from the installed lucide package.
 *
 * Obsidian's `setIcon` draws Lucide glyphs. The port needs the same glyphs, but
 * the plugin names some of them dynamically (tab icons, habit icons coming from
 * data), so the list cannot be a hand-written handful: this script scans the
 * ported source for every Lucide-looking name and emits those icons, so a name
 * that appears in the source is guaranteed to draw.
 *
 * Run: `node tools/gen-icons.mjs <appDir> <outFile>`
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

const appDir = path.resolve(process.argv[2] ?? path.join(root, 'app/src'));
const outFile = path.resolve(process.argv[3] ?? path.join(root, 'shim/icons.generated.ts'));

const lucideRoots = [
  path.resolve(root, 'node_modules/lucide/dist/esm/icons'),
  path.resolve(root, '../dsh-annotation/node_modules/lucide/dist/esm/icons'),
  '/Users/feifan/FEIFAN/08-系统/07github/feifan-life/node_modules/lucide/dist/esm/icons',
];
const lucideDir = lucideRoots.find((candidate) => fs.existsSync(candidate));
if (!lucideDir) throw new Error('lucide icon directory not found');

const available = new Map();
for (const file of fs.readdirSync(lucideDir)) {
  if (!file.endsWith('.js') || file.endsWith('.map')) continue;
  available.set(file.slice(0, -3), path.join(lucideDir, file));
}

/** Names the plugin resolves through variables, plus shell chrome of the port. */
const EXPLICIT = [
  'check', 'x', 'plus', 'ellipsis', 'chevron-down', 'search', 'settings', 'sun-moon',
  'target', 'pencil', 'trash-2', 'archive', 'circle-check', 'image', 'compass',
  'list-checks', 'square-kanban', 'wallet-cards', 'undo-2', 'refresh-cw',
  'calendar-range', 'layout-dashboard', 'kanban', 'wallet', 'flame', 'clipboard-list',
  'lightbulb', 'gift', 'sparkles', 'badge-check', 'lock-keyhole', 'file-text',
  'info', 'user-round', 'command', 'loader-circle', 'maximize-2', 'minimize-2', 'house',
];

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.(ts|tsx|js|css)$/.test(entry.name)) out.push(full);
  }
  return out;
}

const sources = walk(appDir).concat(walk(path.join(root, 'shim')).filter((f) => !f.endsWith('icons.generated.ts')));
const names = new Set(EXPLICIT);
for (const file of sources) {
  const text = fs.readFileSync(file, 'utf8');
  for (const match of text.matchAll(/'([a-z][a-z0-9]*(?:-[a-z0-9]+){0,3})'/g)) {
    if (available.has(match[1])) names.add(match[1]);
  }
}

const entries = [];
const missing = [];
for (const name of [...names].sort()) {
  const file = available.get(name);
  if (!file) {
    missing.push(name);
    continue;
  }
  const text = fs.readFileSync(file, 'utf8');
  const arrayStart = text.indexOf('const ');
  const bracket = text.indexOf('[', arrayStart);
  const lastBracket = text.lastIndexOf(']');
  if (bracket < 0 || lastBracket < 0) continue;
  const literal = text.slice(bracket, lastBracket + 1);
  /* eslint-disable-next-line no-new-func */
  const node = Function('"use strict";return (' + literal + ');')();
  entries.push([name, node]);
}

const body = entries
  .map(([name, node]) => '  ' + JSON.stringify(name) + ': ' + JSON.stringify(node) + ',')
  .join('\n');

const output = `/* Generated by tools/gen-icons.mjs from lucide (ISC). Do not edit by hand. */
export type IconNode = Array<[string, Record<string, string | number>]>;
export const FALLBACK_ICON = 'info';
export const ICON_NAMES: string[] = ${JSON.stringify(entries.map(([name]) => name))};
export const ICONS: Record<string, IconNode> = {
${body}
};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output);
console.log(
  'icons: ' + entries.length + ' glyphs -> ' + path.relative(root, outFile) +
  (missing.length ? ' (not in lucide: ' + missing.join(', ') + ')' : ''),
);
