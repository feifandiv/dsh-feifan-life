/**
 * Build the DSH client artifact for the Feifan Life port.
 *
 * Output is one `client.js` in the module-loader format the Harness serves:
 * `window.__ModuleLoader__.load({ id, factory })`. Inside the factory the
 * plugin's original TypeScript is CJS-bundled with `obsidian` aliased to the
 * browser shim, so the ported source stays unmodified in behaviour.
 *
 * Sources of tooling are resolved from a nearby checkout (`feifan-life` owns
 * esbuild/typescript as devDependencies); nothing is installed into the plugin.
 *
 * Usage: node build.mjs [build|typecheck]
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = here;
const mode = process.argv[2] ?? 'build';

const TOOL_DIRS = [
  path.resolve(root, 'node_modules'),
  path.resolve(root, '../../07github/feifan-life/node_modules'),
  '/Users/feifan/FEIFAN/08-系统/07github/feifan-life/node_modules',
  path.resolve(root, 'node_modules'),
];

function resolveTool(pkg) {
  for (const dir of TOOL_DIRS) {
    const candidate = path.join(dir, pkg);
    if (fs.existsSync(candidate)) return candidate;
  }
  throw new Error(pkg + ' not found in: ' + TOOL_DIRS.join(', '));
}

async function loadEsbuild() {
  const pkgDir = resolveTool('esbuild');
  const require = createRequire(path.join(pkgDir, 'package.json'));
  return require('esbuild');
}

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const readIfExists = (relative) => (fs.existsSync(path.join(root, relative)) ? fs.readFileSync(path.join(root, relative), 'utf8') : '');
const write = (relative, text) => {
  fs.mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
  fs.writeFileSync(path.join(root, relative), text);
  return Buffer.byteLength(text);
};

function log(message) {
  console.log('[build] ' + message);
}

/* --------------------------------------------------------------- typecheck */

if (mode === 'typecheck') {
  const tscDir = resolveTool('typescript');
  const require = createRequire(path.join(tscDir, 'package.json'));
  const ts = require('typescript');
  const files = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith('.ts')) files.push(full);
    }
  };
  walk(path.join(root, 'shim'));
  walk(path.join(root, 'app/src')); 
  const program = ts.createProgram(files, {
    noEmit: true,
    target: ts.ScriptTarget.ES2020,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    allowJs: true,
    strict: false,
    skipLibCheck: true,
    lib: ['lib.es2020.d.ts', 'lib.dom.d.ts'],
    baseUrl: root,
    paths: { obsidian: [path.join(root, 'shim/obsidian.ts')] },
    types: [],
  });
  const diagnostics = ts.getPreEmitDiagnostics(program);
  if (!diagnostics.length) {
    log('typecheck clean');
    process.exit(0);
  }
  for (const diagnostic of diagnostics.slice(0, 40)) {
    const message = ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n');
    if (diagnostic.file && diagnostic.start !== undefined) {
      const position = diagnostic.file.getLineAndCharacterOfPosition(diagnostic.start);
      console.error(
        path.relative(root, diagnostic.file.fileName) + ':' +
        (position.line + 1) + ':' + (position.character + 1) + ' ' + message,
      );
    } else {
      console.error(message);
    }
  }
  process.exit(1);
}

/* ------------------------------------------------------------------- build */

const esbuild = await loadEsbuild();

log('generating icon table');
execFileSync(process.execPath, [path.join(root, 'tools/gen-icons.mjs'), path.join(root, 'app/src'), path.join(root, 'shim/icons.generated.ts')], {
  stdio: 'inherit',
});

log('bundling plugin stylesheet');
const cssResult = await esbuild.build({
  entryPoints: [path.join(root, 'app/src/styles.css')],
  bundle: true,
  write: false,
  outfile: 'fl-app.css',
  loader: { '.jpg': 'dataurl', '.png': 'dataurl', '.woff2': 'dataurl' },
  target: 'es2020',
  logLevel: 'warning',
});
const appCss = cssResult.outputFiles.map((file) => file.text).join('\n');
const baseCss = readIfExists('shim/obsidian-base.css');
const shellCss = readIfExists('shim/shell.css');
const portCss = readIfExists('shim/port.css');

write('shim/styles.generated.ts', `/* Generated by build.mjs. Do not edit by hand. */
export const APP_CSS: string = ${JSON.stringify(appCss)};
export const BASE_CSS: string = ${JSON.stringify(baseCss)};
export const SHELL_CSS: string = ${JSON.stringify(shellCss)};
export const PORT_CSS: string = ${JSON.stringify(portCss)};
`);
log('styles: app ' + Math.round(appCss.length / 1024) + 'kB, base ' + Math.round(baseCss.length / 1024) + 'kB, shell ' + Math.round(shellCss.length / 1024) + 'kB');

log('bundling client half');
const jsResult = await esbuild.build({
  entryPoints: [path.join(root, 'shim/entry.ts')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react'],
  alias: { obsidian: path.join(root, 'shim/obsidian.ts') },
  loader: { '.jpg': 'dataurl', '.png': 'dataurl' },
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
  outfile: 'fl-client.cjs',
});
const clientJs = jsResult.outputFiles.map((file) => file.text).join('\n');

const wrapper = `/*!
 * ${pkg.name} ${pkg.version} — 非凡人生 for DeepSeek Harness
 * Plugin UI ported from the user's Obsidian plugin 非凡人生 (command-center).
 * Original UI: GPL-3.0-only, (c) 非凡. Obsidian API shim: same license.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    "use strict";
    var React = require('react');
    globalThis.__FL_REACT__ = React;
    var module = { exports: {} };
    var exports = module.exports;
${clientJs}
    var api = module.exports;
    return { inject: api.inject || [], apply: api.apply };
  },
});
`;

const bytes = write('client.js', wrapper);
log('wrote client.js (' + Math.round(bytes / 1024) + 'kB)');

// A cheap structural check: the loader contract and both halves must be present.
const output = fs.readFileSync(path.join(root, 'client.js'), 'utf8');
const failures = [];
if (!output.startsWith('/*!')) failures.push('missing banner');
if (!output.includes('window.__ModuleLoader__.load({')) failures.push('missing module loader call');
if (!output.includes('factory(require)')) failures.push('missing factory');
if (!output.includes('return { inject: api.inject || [], apply: api.apply };')) failures.push('missing exports bridge');
if (!output.includes('command-center-view')) failures.push('plugin view type missing from bundle');
if (failures.length) {
  console.error('[build] client.js validation failed: ' + failures.join('; '));
  process.exit(1);
}
log('client.js validation passed');
